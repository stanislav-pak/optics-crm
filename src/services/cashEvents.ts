// Событие «деньги в кассе изменились».
//
// Итог кассы (cash_sessions.system_*) — это кэш: он пересчитывается и
// перезаписывается только когда CashSessionCard монтируется при открытой смене.
// Раньше кассу обновляли лишь два события — доплата мастерской и возврат
// продажи. Погашение долга, новая продажа и расход не обновляли ничего, поэтому
// цифра оставалась старой, а при закрытии смены замерзала в истории навсегда
// (реальный случай: погашение 3000 ₸ по Kaspi не попало в кассу филиала «Гум»).
//
// Механизм намеренно тот же, что уже работал для доплаты мастерской:
// window-событие → слушатель в InventoryPage → перемонтирование CashSessionCard.
export const CASH_CHANGED_EVENT = 'cash-changed';

/** Дёрнуть после любой операции, меняющей деньги смены. */
export function notifyCashChanged(): void {
  window.dispatchEvent(new CustomEvent(CASH_CHANGED_EVENT));
}
